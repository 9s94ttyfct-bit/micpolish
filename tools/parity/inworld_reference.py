"""PyTorch CPU reference output of Inworld Voice Isolator v1 (offline) for parity tests.

Runs the upstream package (inworld-ai/voice-isolator, Apache-2.0, pinned commit
above) exactly as a user would: `VoiceIsolator.load(<denoiser.safetensors>,
device="cpu", precision="fp32", mode="offline").isolate(x, 48000)`, which
renders the clip in the checkpoint's own overlapping windows (8 s, 2 s linear
crossfade for `voice-isolator-v1`).

    uv run tools/parity/inworld_reference.py --input in.wav --output ref.f32
    uv run tools/parity/inworld_reference.py --make-fixtures Tests/Fixtures/inworld
    uv run tools/parity/inworld_reference.py --check-goldens <voice-isolator>/tests/fixtures

The weights are `inworld/voice-isolator` revision 9b0285b3… `denoiser.safetensors`
(SHA-256 checked); pass `--weights` to use a local copy. The output is raw
little-endian float32 samples at 48 kHz, as many as the input.
"""

import argparse
import hashlib
import io
import json
import pathlib
import urllib.request

import numpy as np
import soundfile as sf
import torch
from huggingface_hub import hf_hub_download

from inworld.voice_isolation import isolator

MODEL_REPO = "inworld/voice-isolator"
MODEL_REVISION = "9b0285b3fe8403aa8e2f1dbb2165a80a4294c970"
MODEL_FILE = "denoiser.safetensors"
MODEL_SHA256 = "647335a6aeb4dc706b895532c209d51e0e84a4849d17b339f00d4392a050ae53"
UPSTREAM_COMMIT = "c73b3fab81a870410cbac50d2f05f25edc4d10aa"
SAMPLE_RATE = 48_000
REPO_ROOT = pathlib.Path(__file__).resolve().parents[2]

# Upstream demo examples (LibriSpeech dev-clean utterances, CC BY 4.0, mixed with
# noise generated by upstream demo/build_examples.py).
DEMO_EXAMPLES = {
    "sample_14.wav": "b475f5ce2d752d6607b2fd1bcd7e7fa7572538f031e8a367d57582c3bf22400c",
    "sample_15.wav": "b9af1139e24dc8cc438d4cb5cf07f401ccc123c4c8095206596db1c6247f51cf",
}
# 15.8 s: more than two 8 s windows at a 6 s stride (three windows), and the
# length is not a multiple of the 480-sample hop, so the last window is placed
# at the clip's end, off the stride.
STREAM_SAMPLES = 760_123
# 3.98 s, also not a multiple of the hop.
NOISY_SAMPLES = 191_000
NOISY_SEED = 20261122


def sha256(path) -> str:
    return hashlib.sha256(pathlib.Path(path).read_bytes()).hexdigest()


def weights_path(path):
    if path is None:
        path = hf_hub_download(MODEL_REPO, MODEL_FILE, revision=MODEL_REVISION)
    digest = sha256(path)
    if digest != MODEL_SHA256:
        raise SystemExit(f"{path}: SHA-256 {digest} != pinned {MODEL_SHA256}")
    return path


def load_isolator(path):
    torch.set_num_threads(1)
    return isolator.VoiceIsolator.load(path, device="cpu", precision="fp32", mode="offline")


def read_mono(path):
    audio, sr = sf.read(path, dtype="float32", always_2d=True)
    if sr != SAMPLE_RATE:
        raise SystemExit(f"{path}: expected {SAMPLE_RATE} Hz, got {sr}")
    if audio.shape[1] != 1:
        raise SystemExit(f"{path}: expected mono, got {audio.shape[1]} channels")
    return audio[:, 0].copy()


def fetch_demo_example(name):
    url = f"https://raw.githubusercontent.com/inworld-ai/voice-isolator/{UPSTREAM_COMMIT}/demo/examples/{name}"
    data = urllib.request.urlopen(url, timeout=120).read()
    digest = hashlib.sha256(data).hexdigest()
    if digest != DEMO_EXAMPLES[name]:
        raise SystemExit(f"{url}: SHA-256 {digest} != pinned {DEMO_EXAMPLES[name]}")
    audio, sr = sf.read(io.BytesIO(data), dtype="int16")
    assert sr == SAMPLE_RATE and audio.ndim == 1
    return audio


def make_fixtures(directory):
    """Writes the two PCM16 parity inputs (deterministic: seeded numpy noise)."""
    directory = pathlib.Path(directory)
    directory.mkdir(parents=True, exist_ok=True)

    # Band-limited speech (no content above 8 kHz) plus generated noise:
    # full-band hiss, mains hum with harmonics and short clicks, ~6 dB SNR.
    speech = read_mono(REPO_ROOT / "Tests/Fixtures/lava/speech_8k_band.wav")[:NOISY_SAMPLES].astype(np.float64)
    rng = np.random.Generator(np.random.PCG64(NOISY_SEED))
    t = np.arange(NOISY_SAMPLES) / SAMPLE_RATE
    hiss = rng.standard_normal(NOISY_SAMPLES)
    hum = sum(np.sin(2 * np.pi * f * t + k) / k for k, f in enumerate((60, 120, 180, 240), 1))
    clicks = np.zeros(NOISY_SAMPLES)
    for start in rng.integers(0, NOISY_SAMPLES - 960, size=6):
        clicks[start:start + 960] += 6 * rng.standard_normal(960) * np.exp(-np.arange(960) / 120)
    noise = hiss / np.sqrt(np.mean(hiss**2)) + 0.7 * hum / np.sqrt(np.mean(hum**2)) + clicks
    speech_rms = np.sqrt(np.mean(speech**2))
    noise *= speech_rms / (10 ** (6 / 20) * np.sqrt(np.mean(noise**2)))
    mixture = speech + noise
    mixture *= min(1.0, 0.9 / np.max(np.abs(mixture)))
    sf.write(directory / "noisy_4s.wav", mixture, SAMPLE_RATE, subtype="PCM_16")

    # The two generated upstream demo examples back to back, PCM16 copied as is.
    joined = np.concatenate([fetch_demo_example(name) for name in DEMO_EXAMPLES])[:STREAM_SAMPLES]
    sf.write(directory / "stream_16s.wav", joined, SAMPLE_RATE, subtype="PCM_16")
    for name in ("noisy_4s.wav", "stream_16s.wav"):
        print(f"{name}: SHA-256 {sha256(directory / name)}")


def render(vi, x):
    out = vi.isolate(x, SAMPLE_RATE)
    out = np.asarray(out, dtype=np.float32)
    if out.shape != x.shape:
        raise SystemExit(f"isolate returned {out.shape} for {x.shape}")
    return out


def check_goldens(vi, directory):
    """Upstream's own golden offline fixtures at their recorded tolerance; exits 1 if any fails."""
    failed = []
    for meta_path in sorted(pathlib.Path(directory).glob("offline_*/meta.json")):
        meta = json.loads(meta_path.read_text())
        x = read_mono(meta_path.parent / "input.wav")
        expected = np.load(meta_path.parent / "expected.npy")
        y = render(vi, x)
        err = float(np.abs(y - expected).max())
        rel = float(np.sqrt(np.sum((y - expected) ** 2) / np.sum(expected**2)))
        ok = err <= meta["tolerance"]
        print(f"{meta_path.parent.name}: max abs {err:.3g} (tolerance {meta['tolerance']:g}), "
              f"relative RMSE {rel:.3g} {'OK' if ok else 'FAIL'}")
        if not ok:
            failed.append(meta_path.parent.name)
    if failed:
        raise SystemExit(f"golden fixtures outside tolerance: {', '.join(failed)}")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--weights", help="local denoiser.safetensors (default: download the pinned revision)")
    parser.add_argument("--input")
    parser.add_argument("--output")
    parser.add_argument("--make-fixtures", metavar="DIR", help="write the parity input WAVs into DIR")
    parser.add_argument("--check-goldens", metavar="DIR", help="upstream tests/fixtures directory")
    args = parser.parse_args()

    if args.make_fixtures:
        make_fixtures(args.make_fixtures)
    if not (args.input or args.check_goldens):
        if not args.make_fixtures:
            parser.error("nothing to do")
        return

    vi = load_isolator(weights_path(args.weights))
    config = vi.model.config
    print(f"config: chunk {config.chunk_seconds} s, overlap {config.overlap_seconds} s, "
          f"n_fft {config.n_fft}, hop {config.hop_length}, offline_passes {vi.offline_passes}, "
          f"bands {len(vi.model.edges)}")
    if args.check_goldens:
        check_goldens(vi, args.check_goldens)
    if args.input:
        if not args.output:
            parser.error("--output is required with --input")
        x = read_mono(args.input)
        y = render(vi, x)
        y.astype("<f4").tofile(args.output)
        print(f"wrote {len(y)} samples at {SAMPLE_RATE} Hz to {args.output}")


if __name__ == "__main__":
    main()
